def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for p in products:
        pid = p["id"]
        p["image"] = f"{IMG_BASE}_product_{pid}.jpg"
        p["images"] = [
            f"{IMG_BASE}_product_{pid}.jpg",
            f"{IMG_BASE}_product_slice_{pid}.jpg",
        ]

    data = {
        "date": TODAY,
        "totalProducts": len(products),
        "products": products,
    }
    out = os.path.join(OUT_DIR, "data.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    # schema 校验
    for p in data["products"]:
        assert "image" in p, f"❌ product {p['id']} 缺 image 字段"
        assert p["image"].startswith("https://"), f"❌ product {p['id']} image 必须 CDN URL"
        assert "images" in p and len(p["images"]) >= 1, f"❌ product {p['id']} 缺 images 数组"
        assert len(p["desc"]) >= 150, f"❌ product {p['id']} desc 不足 150 字"
        assert len(p["highlights"]) == 5, f"❌ product {p['id']} highlights 必须 5 条"
        assert len(p["tags"]) == 5, f"❌ product {p['id']} tags 必须 5 个"
    print(f"✅ data.json 生成并通过 schema 校验 → {out}")
    for p in data["products"]:
        print(f"   [{p['id']}] {p['name'][:34]} | {p['category']} | {p['price']} | desc {len(p['desc'])}字")


if __name__ == "__main__":
    main()
